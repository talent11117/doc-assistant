# ------------------------------------------------------------
# 第 1 节：为什么需要类？先看没有类的时候有多烦
# ------------------------------------------------------------
#
# 你已经会写函数了。假设要给好几个人记成绩：
#
#     zhangsan_scores = {}
#     lisi_scores = {}
#
#     def add_score(scores, course, score):
#         scores[course] = score
#
#     def average_score(scores):
#         ...
#
# 用的时候每次都得把 scores 传进去：
#
#     add_score(zhangsan_scores, "数学", 80)
#     add_score(lisi_scores, "数学", 90)
#     print(average_score(zhangsan_scores))
#
# 问题在哪？
#
#   1. 每加一个人，就多一个变量（wangwu_scores...）
#   2. 每次调用都得记住"要传哪个 scores"
#   3. 万一传错了，把李四的成绩加到张三本上，程序不报错，结果悄悄错
#
# 类就是把「数据」和「操作数据的函数」打包在一起，解决这个问题：
#
#     zhangsan = ScoreBook("张三")     # 造一个"张三的成绩本"
#     zhangsan.add("数学", 80)         # 不用再传 scores 了
#     print(zhangsan.average())
#
# 数据（成绩）就存在 zhangsan 这个对象身上，不用你每次手动传。


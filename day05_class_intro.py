# ------------------------------------------------------------
# 第 2 节：一个最小的类
# ------------------------------------------------------------

class Dog:
    # __init__ 里的 self 就是"正在被造出来的这只狗"
    def __init__(self, name):
        self.name = name        # 把名字记在"这只狗自己"身上

    def bark(self):
        return self.name + "：汪汪！"


d = Dog("旺财")
print("第2节：", d.bark())

# 输出：旺财：汪汪！
#
# 逐行拆开看：
#
#   class Dog:              定义模板，叫 Dog
#   def __init__(self, name)  造对象时自动执行的函数
#   self.name = name        把参数 name 存到"自己身上"，起名叫 name
#   def bark(self)          类里面的函数叫"方法"，第一个参数永远是 self
#   d = Dog("旺财")          按模板造一个对象，赋给 d
#   d.bark()                调用 d 的 bark 方法
#
# ⚠️ 注意 d.bark() 括号里是空的！
#    但 bark 定义时写着 def bark(self)。
#    那个 self 是 Python 自动塞进去的，不用你手动传。


# ------------------------------------------------------------
# 第 3 节：self 到底是什么？
# ------------------------------------------------------------
#
# self 就是"这个对象本身"。Python 在调用 d.bark() 时，
# 实际做的事相当于 Dog.bark(d) —— 把 d 当第一个参数传进去了。
#
# 记住一句话就够了：
#   self 是"我"，不是"我们"。
#
# self.name 的意思是"我这个对象的名字"，
# 不是"所有 Dog 对象的名字"。
#
# 下面这段证明给你看：

class Cat:
    def __init__(self, name):
        self.name = name

c1 = Cat("小白")
c2 = Cat("小橘")

print("第3节：c1 叫", c1.name)
print("第3节：c2 叫", c2.name)

c1.name = "改了个名字"

print("第3节：改完之后 c1 叫", c1.name)
print("第3节：改完之后 c2 叫", c2.name)

# 输出：
#   c1 叫 小白
#   c2 叫 小橘
#   改完之后 c1 叫 改了个名字
#   改完之后 c2 叫 小橘      ← c2 完全没受影响！
#
# 因为 c1.name 和 c2.name 是两份独立的数据。


# ------------------------------------------------------------
# 第 4 节：⚠️ 一个最容易犯的错（今天的重点）
# ------------------------------------------------------------
#
# 把属性写在 __init__ 外面，会变成"所有对象共用一个"：

class BadDog:
    tricks = []              # ← 写在方法外面，所有 BadDog 共用这一个列表！

    def __init__(self, name):
        self.name = name

    def learn(self, trick):
        self.tricks.append(trick)


a = BadDog("阿黄")
b = BadDog("阿黑")

a.learn("坐下")

print("第4节：阿黄会", a.tricks)
print("第4节：阿黑会", b.tricks)

# 输出：
#   阿黄会 ['坐下']
#   阿黑会 ['坐下']      ← 阿黑啥也没学，但也会了！
#
# 因为 tricks 是写在 class 下面的，所有 BadDog 对象共用同一个列表。
# a 往里加东西，b 也跟着变。这是 bug，而且不报错，极难发现。
#
# ✅ 正确的写法是写在 __init__ 里面：
#
#     class GoodDog:
#         def __init__(self, name):
#             self.name = name
#             self.tricks = []        # ← 在这里，每个对象各有一份
#
# 今天的作业里，self.scores = {} 必须写在 __init__ 里面，就是这个原因。
# 自测第 5 条会专门检查这个。


# ------------------------------------------------------------
# 第 5 节：方法 —— 类里面的函数
# ------------------------------------------------------------
#
# 方法和你之前写的函数没区别，只是多了一个 self，而且能直接用 self 上的数据。

class Counter:
    def __init__(self):
        self.count = 0

    def add_one(self):
        self.count = self.count + 1

    def show(self):
        return "现在是 " + str(self.count)


box = Counter()
box.add_one()
box.add_one()
box.add_one()
print("第5节：", box.show())

# 输出：现在是 3
#
# 对比一下：
#   你之前写的函数：add_one(count) 要传参数，还要 return 新值
#   现在的方法：    box.add_one()  直接改自己身上的 count，不用传也不用 return
#
# 这就是类最方便的地方：数据就在对象身上，方法伸手就能拿到。


